"""Typed exception hierarchy for clean error boundaries."""


class VRAGError(Exception):
    """Base error."""


class ConfigError(VRAGError): ...
class ExtractionError(VRAGError): ...
class EmbeddingError(VRAGError): ...
class VectorStoreError(VRAGError): ...
class RetrievalError(VRAGError): ...
class LLMError(VRAGError): ...
class VisionError(LLMError): ...
class RoutingError(VRAGError): ...
class CompactionError(VRAGError): ...
class ConfidenceError(VRAGError): ...
class ValidationError(VRAGError): ...
